    fun vector(name: String): ImageVector? = byName[name]?.vector

    fun search(q: String): List<CatalogIcon> {
        val n = q.trim().lowercase()
        return if (n.isEmpty()) all else all.filter { it.name.contains(n) || it.words.contains(n) }
    }

